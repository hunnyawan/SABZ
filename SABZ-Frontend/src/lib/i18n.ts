const LANG_STORAGE_KEY = 'sabz.lang';

function detectInitialLanguage(): Language {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved === 'ur' || saved === 'en') return saved;
  } catch {
    // Storage unavailable (private mode/quota) — fall back to English.
  }
  return 'en';
}

let currentLang: Language = detectInitialLanguage();

function applyDocumentLanguage(lang: Language) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ur' ? 'rtl' : 'ltr';
}

// Apply the persisted language before first render so the layout direction
// is correct from the very first paint (Urdu = RTL).
applyDocumentLanguage(currentLang);

export function setLanguage(lang: Language) {
  currentLang = lang;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    // Storage unavailable — language still applies for this session.
  }
  applyDocumentLanguage(lang);
}

export function getLanguage(): Language {
  return currentLang;
}

export function t(key: string): string {
  const strings = currentLang === 'ur' ? ur : en;
  return strings[key] ?? en[key] ?? key;
}

export function isRtl(): boolean {
  return currentLang === 'ur';
}
